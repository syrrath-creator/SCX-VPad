//! Original input-only simulation personas. Usage IDs are USB-IF HID Usage
//! Tables interoperability constants, also declared by Windows SDK hidusage.h.
//! https://www.usb.org/hid
//! https://learn.microsoft.com/windows-hardware/drivers/hid/hid-usages
//!
//! Wire layout stays Report1 + buttons32 + hat/padding8 + signed16*4 + unsigned16*2.
//! InputState fields, in wire order:
//! Wheel: left_x=Steering; left_y=Y auxiliary; right_x=Rx auxiliary;
//!        right_y=Ry auxiliary; left_trigger=Accelerator; right_trigger=Brake.
//! Flight: left_x=X; left_y=Y; right_x=Rz rudder; right_y=Rx auxiliary;
//!         left_trigger=Throttle; right_trigger=Brake.
//! No PID force-feedback collection, no rumble, no XInput persona is advertised.
//! Games must accept HID/DirectInput controls and may require manual assignment.

macro_rules! descriptor {
    ($a_page:expr,$a:expr,$b_page:expr,$b:expr,$c_page:expr,$c:expr,$d_page:expr,$d:expr,$e_page:expr,$e:expr,$f_page:expr,$f:expr) => {
        &[
            0x05, 0x01, 0x09, 0x04, 0xa1, 0x01, // Generic Desktop / Joystick
            0x85, 0x01, 0x05, 0x09, 0x19, 0x01, 0x29, 0x20, // 32 independent buttons
            0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x20, 0x81, 0x02, 0x05, 0x01, 0x09,
            0x39, // Hat switch, 8 means neutral/null
            0x15, 0x00, 0x25, 0x07, 0x35, 0x00, 0x46, 0x3b, 0x01, 0x65, 0x14, 0x75, 0x04, 0x95,
            0x01, 0x81, 0x42, 0x75, 0x04, 0x95, 0x01, 0x81, 0x03, 0x65, 0x00, 0x35, 0x00, 0x45,
            0x00, 0x16, 0x00, 0x80, 0x26, 0xff, 0x7f, // -32768..32767
            // Extended local usages carry their own page (little endian u32).
            0x0b, $a, 0x00, $a_page, 0x00, 0x0b, $b, 0x00, $b_page, 0x00, 0x0b, $c, 0x00, $c_page,
            0x00, 0x0b, $d, 0x00, $d_page, 0x00, 0x75, 0x10, 0x95, 0x04, 0x81, 0x02, 0x15, 0x00,
            0x27, 0xff, 0xff, 0x00, 0x00, // 0..65535, independent pedals
            0x0b, $e, 0x00, $e_page, 0x00, 0x0b, $f, 0x00, $f_page, 0x00, 0x75, 0x10, 0x95, 0x02,
            0x81, 0x02, 0xc0,
            // Separate authenticated producer collection; never a second pad.
            0x06, 0x53, 0xff, 0x09, 0x01, 0xa1, 0x01, 0x85, 0x7a, 0x09, 0x02, 0x15, 0x00, 0x26,
            0xff, 0x00, 0x75, 0x08, 0x95, 0x60, 0xb1, 0x02, 0x85, 0x7f, 0x09, 0x03, 0x95, 0x20,
            0xb1, 0x02, 0xc0,
        ]
    };
}
pub static WHEEL: &[u8] = descriptor!(2, 0xc8, 1, 0x31, 1, 0x33, 1, 0x34, 2, 0xc4, 2, 0xc5);
pub static FLIGHT_STICK: &[u8] = descriptor!(1, 0x30, 1, 0x31, 1, 0x35, 1, 0x33, 2, 0xbb, 2, 0xc5);
